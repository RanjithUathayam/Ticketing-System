#!/usr/bin/env node
// scripts/generate-features.mjs
//
// Auto-discovery codegen for the "Operations Tools" feature pages.
//
// Scans src/features/*/ for feature folders (any folder containing a
// feature.meta.json + index.ts) and writes src/features/features.generated.ts,
// which exports:
//   - FEATURE_MENU     : sorted menu metadata, consumed by the sidebar
//   - featureRoutes    : an Angular Routes array, consumed by app.routes.ts
//
// Nothing else in the app needs to change when a page is added, removed,
// reordered, or disabled — see src/features/README.md.
//
// Usage:
//   node scripts/generate-features.mjs          # generate once
//   node scripts/generate-features.mjs --watch  # regenerate on change (dev)
//
// Wired into `npm run predev` / `npm run prebuild` so `npm run dev` and
// `npm run build` always pick up new pages automatically.

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, watch } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const FEATURES_DIR = join(ROOT, 'src', 'features');
const OUT_FILE = join(FEATURES_DIR, 'features.generated.ts');

const REQUIRED_FIELDS = ['key', 'title', 'menuLabel', 'path', 'icon', 'group', 'order', 'enabled'];

function discoverFeatures() {
  if (!existsSync(FEATURES_DIR)) return [];

  const entries = readdirSync(FEATURES_DIR).filter(name => {
    const full = join(FEATURES_DIR, name);
    return statSync(full).isDirectory();
  });

  const features = [];
  for (const folder of entries) {
    const metaPath = join(FEATURES_DIR, folder, 'feature.meta.json');
    const indexPath = join(FEATURES_DIR, folder, 'index.ts');

    if (!existsSync(metaPath)) continue; // not a feature folder (e.g. a shared-utility folder)

    if (!existsSync(indexPath)) {
      console.warn(`[generate-features] skipping "${folder}": feature.meta.json present but index.ts is missing.`);
      continue;
    }

    let meta;
    try {
      meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    } catch (err) {
      console.warn(`[generate-features] skipping "${folder}": feature.meta.json is not valid JSON (${err.message}).`);
      continue;
    }

    const missing = REQUIRED_FIELDS.filter(f => !(f in meta));
    if (missing.length) {
      console.warn(`[generate-features] skipping "${folder}": feature.meta.json is missing field(s): ${missing.join(', ')}.`);
      continue;
    }

    if (meta.key !== folder) {
      console.warn(`[generate-features] "${folder}": meta.key ("${meta.key}") does not match its folder name — using the folder name as the source of truth for the route/import path, but keeping meta.key for display purposes.`);
    }

    features.push({ folder, meta });
  }

  // Guard against duplicate paths/keys, which would otherwise produce a silently
  // broken route table (Angular just uses the first match).
  const byPath = new Map();
  const byKey = new Map();
  for (const { folder, meta } of features) {
    if (byPath.has(meta.path)) {
      throw new Error(`[generate-features] duplicate route path "${meta.path}" in "${folder}" and "${byPath.get(meta.path)}". Each feature.meta.json needs a unique "path".`);
    }
    byPath.set(meta.path, folder);
    if (byKey.has(meta.key)) {
      throw new Error(`[generate-features] duplicate feature key "${meta.key}" in "${folder}" and "${byKey.get(meta.key)}". Each feature.meta.json needs a unique "key".`);
    }
    byKey.set(meta.key, folder);
  }

  features.sort((a, b) => {
    if (a.meta.group !== b.meta.group) return a.meta.group.localeCompare(b.meta.group);
    if (a.meta.order !== b.meta.order) return a.meta.order - b.meta.order;
    return a.meta.title.localeCompare(b.meta.title);
  });

  return features;
}

function render(features) {
  const menuEntries = features.map(({ meta }) => `  ${JSON.stringify(meta)}`).join(',\n');

  const routeEntries = features
    .map(({ folder, meta }) => `  {
    path: ${JSON.stringify(meta.path)},
    title: ${JSON.stringify(meta.title + ' — Uathayam Operations')},
    loadComponent: () => import('./${folder}/index').then(m => m.FeatureComponent),
    data: { featureKey: ${JSON.stringify(meta.key)}, enabled: ${meta.enabled} },
  }`)
    .join(',\n');

  return `// src/features/features.generated.ts
// AUTO-GENERATED by scripts/generate-features.mjs — do not edit by hand.
// Regenerate with \`npm run generate:features\` (also runs automatically
// before \`npm run dev\` / \`npm run build\`).
//
// Discovered ${features.length} feature page(s) at ${new Date().toISOString()}.
import { Routes } from '@angular/router';
import { FeaturePageMeta } from './feature.types';

export const FEATURE_MENU: FeaturePageMeta[] = [
${menuEntries}
];

export const featureRoutes: Routes = [
${routeEntries}
];
`;
}

function generate() {
  const features = discoverFeatures();
  const output = render(features);
  writeFileSync(OUT_FILE, output, 'utf8');
  console.log(`[generate-features] wrote ${features.length} feature page(s) to ${OUT_FILE.replace(ROOT, '.')}`);
  for (const { meta } of features) {
    console.log(`  - /ops/${meta.path}  (${meta.group} › ${meta.menuLabel})${meta.enabled ? '' : '  [disabled]'}`);
  }
}

const watchMode = process.argv.includes('--watch');

generate();

if (watchMode) {
  console.log('[generate-features] watching src/features for changes... (Ctrl+C to stop)');
  watch(FEATURES_DIR, { recursive: true }, (_event, filename) => {
    if (!filename) return;
    if (filename.endsWith('features.generated.ts')) return; // ignore our own output
    if (!(filename.endsWith('feature.meta.json') || filename.endsWith('index.ts'))) return;
    try {
      generate();
    } catch (err) {
      console.error(err.message);
    }
  });
}
